/** UMD global of a package, as the material builder derives it. */
const libraryOf = (name) =>
  name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')

function render(key) {
  const dir = MATERIALS[key]
  const info = {
    ...INFO[key],
    lib: LIBRARIES[key].pkg,
    vue: LIBRARIES[key].vue,
  }
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const version = pkg.dependencies[info.lib]
  const count = readdirSync(join(dir, 'src/lowcode')).filter((name) =>
    existsSync(join(dir, 'src/lowcode', name, 'meta.ts')),
  ).length
  const library = libraryOf(pkg.name)
  const vue = info.vue === 2 ? 'Vue 2.7' : 'Vue 3'
  const renderer = `@cdlab996/lowcode-vue${info.vue}`
  const cdn = `https://unpkg.com/${pkg.name}@<version>/dist`
  const pinned = info.release ? ` (${info.release})` : ''
  const notes = info.notes ? `\n${info.notes.join('\n')}\n` : ''

  return `# ${pkg.name}

[![npm version](https://img.shields.io/npm/v/${pkg.name}?logo=npm)](https://www.npmjs.com/package/${pkg.name})
[![npm downloads](https://img.shields.io/npm/dm/${pkg.name})](https://www.npmjs.com/package/${pkg.name})

[LowCode Engine](https://github.com/alibaba/lowcode-engine) materials of
[${info.title}](${info.home}) (\`${info.lib}\` ${version}) for **${vue}**, rendered by
\`${renderer}\`.

<!-- Generated by scripts/materials/readme.cjs: edit the script, not this file. -->

## Components

${count} components: every component documented by \`${info.lib}\` ${version}${pinned}
has a meta, with the props, events and slots of [its docs](${info.docs}),
a snippet and a \`docUrl\` to its page.
${notes}
- The metas are generated from the docs of that version (\`scripts/materials\`,
  see CONTRIBUTING.md in the repository); \`${info.lib}\` is pinned to ${version}.
- \`tests/meta.test.ts\` checks them against the components of that version:
  declared props, handler names, doc links, code generation exports and
  screenshots.
- \`screenshots/\` holds a thumbnail of every component, rendered from its
  snippet in the designer canvas; components with nothing to show (modals,
  sub-components) use \`screenshots/fallback.svg\`.

## Usage

The package ships browser builds; the designer loads them through
\`assets.json\`. The canvas must run ${vue} with the
\`${renderer}\` simulator.

From a CDN (unpkg serves the published \`dist\`):

\`\`\`ts
import { injectAssets } from '@alilc/lowcode-plugin-inject'
import type { IPublicModelPluginContext } from '@alilc/lowcode-types'

const editorInit = (ctx: IPublicModelPluginContext) => ({
  async init() {
    const assets = await injectAssets(
      'https://unpkg.com/${pkg.name}/dist/assets.json',
    )
    await ctx.material.setAssets(assets)
  },
})
editorInit.pluginName = 'editorInit'
\`\`\`

From the installed package (\`pnpm add ${pkg.name}\`), serve its \`dist\`
yourself and pass the imported JSON with your own URLs:

\`\`\`ts
import assets from '${pkg.name}/dist/assets.json'
\`\`\`

In the designer of this repository, the material is built in; any other
material is added by pasting its \`assets.json\` URL into the 物料 panel.

## Files

- \`dist/index.js\`, \`dist/index.css\`: the components, as
  \`window.${library}\`
- \`dist/meta.js\`: the metas, as \`window.${library}Meta\`
- \`dist/assets.json\`: the engine assets pointing at the two, with the
  \`codegen\` manifest
- \`dist/screenshots/\`: snippet thumbnails

The scripts, the styles and \`assets.json\` also come minified (\`.min\`).
\`assets.json\` of a release:

\`\`\`json
{
  "version": "<version>",
  "packages": [
    {
      "package": "${pkg.name}",
      "version": "<version>",
      "library": "${library}",
      "urls": [
        "${cdn}/index.css",
        "${cdn}/index.js"
      ],
      "codegen": {
        "exports": { "...": "component -> export of ${info.lib}" },
        "styles": ["..."],
        "dependencies": { "${info.lib}": "${version}" }
      }
    }
  ],
  "components": [
    {
      "exportName": "${library}Meta",
      "url": "${cdn}/meta.js",
      "package": { "npm": "${pkg.name}" }
    }
  ],
  "sort": { "groupList": [], "categoryList": [] }
}
\`\`\`

The \`codegen\` manifest is what the code generator
(\`@cdlab996/lowcode-code-generator\`) uses to import the components from
\`${info.lib}\` in generated projects.

## Development

\`\`\`bash
pnpm -C ${dir.slice(dir.indexOf('packages/'))} build   # dist/
pnpm dev --watch ${dir.split('/').pop()}   # from the repository root: rebuild on change, next to the designer
\`\`\`

## License

[MIT](https://github.com/wuchendi/lowcode-engine-vue/blob/main/LICENSE)
`
}

if (require.main === module) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const key of LIBS) {
    const file = join(MATERIALS[key], 'README.md')
    const text = render(key)
    if (existsSync(file) && readFileSync(file, 'utf8') === text) continue
    if (check) {
      stale++
      console.error(
        `${file} is out of date: run node scripts/materials/readme.cjs`,
      )
    } else {
      writeFileSync(file, text)
      console.log(`wrote ${file}`)
    }
  }
  if (stale) process.exit(1)
}

/** The README a material directory should have. */
const renderDir = (dir) =>
  render(LIBS.find((key) => resolve(MATERIALS[key]) === resolve(dir)))

module.exports = { render, renderDir }
